/** 值放宽成 string，避免 `as const` 把每种语言钉成互不兼容的字面量类型。 */
type Widen<T> = T extends string
  ? string
  : T extends (...args: infer A) => string
    ? (...args: A) => string
    : { [K in keyof T]: Widen<T[K]> };

export type Strings = Widen<typeof zhCN>;
